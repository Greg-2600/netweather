#!/usr/bin/env python3
"""Generate the US hub projection asset and hub marker coordinates.

This is a build-time tool: it fetches public-domain Natural Earth 110m state
boundaries once, projects the contiguous United States with an Albers equal-area
conic projection, and writes internal/web/static/us-projection.svg. It also prints
the hub marker positions as percentage coordinates for hubUSProjectionData in
internal/web/server.go. Nothing in the running app fetches anything.

Usage: python3 scripts/gen_us_projection.py [OUTPUT_SVG]

Source: natural-earth-vector v5.1.2 (public domain), ne_110m_admin_1_states_provinces.geojson
"""

from __future__ import annotations

import json
import math
import sys
import urllib.request

SOURCE = (
    "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/"
    "geojson/ne_110m_admin_1_states_provinces.geojson"
)
OUT = sys.argv[1] if len(sys.argv) > 1 else "internal/web/static/us-projection.svg"
VIEW_W, VIEW_H = 1000.0, 620.0
PAD_X, PAD_Y = 22.0, 22.0

# Standard US Albers parameters: standard parallels 29.5N / 45.5N, origin 37.5N,
# central meridian 96W. These are the conventional CONUS values.
LON0, LAT0, PHI1, PHI2 = -96.0, 37.5, 29.5, 45.5
N = 0.5 * (math.sin(math.radians(PHI1)) + math.sin(math.radians(PHI2)))
C = math.cos(math.radians(PHI1)) ** 2 + 2 * N * math.sin(math.radians(PHI1))
RHO0 = math.sqrt(C - 2 * N * math.sin(math.radians(LAT0))) / N

# Alaska, Hawaii and the territories are deliberately excluded: the projection
# is a contiguous-US frame, and every configured hub city is in CONUS.
EXCLUDE = {"AK", "HI", "PR", "GU", "VI", "AS", "MP"}


def albers(lon: float, lat: float) -> tuple[float, float]:
    theta = N * math.radians(lon - LON0)
    rho = math.sqrt(C - 2 * N * math.sin(math.radians(lat))) / N
    # SVG y grows downward, so negate the map-north-positive value here.
    return rho * math.sin(theta), -(RHO0 - rho * math.cos(theta))


def rings(geometry: dict) -> list[list[list[float]]]:
    kind = geometry["type"]
    if kind == "Polygon":
        return geometry["coordinates"]
    if kind == "MultiPolygon":
        return [ring for polygon in geometry["coordinates"] for ring in polygon]
    return []


def fmt(value: float) -> str:
    return f"{value:.1f}".rstrip("0").rstrip(".")


# The source is a fixed https constant, not user input.
with urllib.request.urlopen(SOURCE, timeout=60) as response:  # nosec B310
    geojson = json.load(response)

states: list[tuple[str, list[list[tuple[float, float]]]]] = []
for feature in geojson["features"]:
    props = feature["properties"]
    if props.get("iso_a2") != "US" or props.get("postal") in EXCLUDE:
        continue
    projected = [
        [albers(lon, lat) for lon, lat in ring]
        for ring in rings(feature["geometry"])
    ]
    if projected and any(projected):
        states.append((props["postal"], projected))

all_points = [pt for _, state in states for ring in state for pt in ring]
min_x = min(pt[0] for pt in all_points)
max_x = max(pt[0] for pt in all_points)
min_y = min(pt[1] for pt in all_points)
max_y = max(pt[1] for pt in all_points)
scale = min((VIEW_W - 2 * PAD_X) / (max_x - min_x), (VIEW_H - 2 * PAD_Y) / (max_y - min_y))
offset_x = PAD_X + ((VIEW_W - 2 * PAD_X) - (max_x - min_x) * scale) / 2
offset_y = PAD_Y + ((VIEW_H - 2 * PAD_Y) - (max_y - min_y) * scale) / 2


def to_view(pt: tuple[float, float]) -> tuple[float, float]:
    return offset_x + (pt[0] - min_x) * scale, offset_y + (pt[1] - min_y) * scale


def path_for(state: list[list[tuple[float, float]]]) -> str:
    pieces = []
    for ring in state:
        mapped = [to_view(pt) for pt in ring]
        pieces.append(
            "M" + " L".join(f"{fmt(x)},{fmt(y)}" for x, y in mapped) + " Z"
        )
    return " ".join(pieces)


lines = [
    (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'viewBox="0 0 {fmt(VIEW_W)} {fmt(VIEW_H)}" role="img" '
        'aria-label="Contiguous United States state outlines, Albers equal-area '
        'conic projection, simplified from Natural Earth 110m admin-1 polygons">'
    ),
    "  <!-- Public-domain Natural Earth 110m admin-1 state polygons, projected with",
    "       an Albers equal-area conic (29.5N/45.5N parallels, 96W meridian).",
    "       Generated by scripts/gen_us_projection.py. No script or external reference. -->",
    f'  <rect width="{fmt(VIEW_W)}" height="{fmt(VIEW_H)}" fill="#0b0f14"/>',
    '  <g fill="#121821" stroke="#1f2a37" stroke-width="0.7">',
]
for postal, state in sorted(states):
    lines.append(f'    <path data-state="{postal}" d="{path_for(state)}"/>')
lines.append("  </g>")
lines.append("</svg>")

with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
    handle.write("\n".join(lines) + "\n")

print(f"wrote {OUT} ({len(states)} states)")

# Recover approximate city lat/lon from the documented equirectangular hub
# anchors in server.go, then project them through the same Albers transform.
# The anchors are already rounded to two decimals, so these are approximate
# city centres, never measured hosting locations.
HUBS = (
    "Dallas, TX:23.11:31.79|New York, NY:29.45:27.38|Newark, NJ:29.40:27.39|"
    "San Francisco, CA:16.00:29.01|Seattle, WA:16.02:23.56|Miami, FL:27.71:35.67|"
    "Houston, TX:23.51:33.48|Minneapolis, MN:24.10:25.01|Detroit, MI:26.93:26.48|"
    "Salt Lake City, UT:18.91:27.35|Phoenix, AZ:18.87:31.42|Raleigh, NC:28.15:30.13|"
    "Las Vegas, NV:18.01:29.91|Washington, DC:28.61:28.39|Orlando, FL:27.39:34.16|"
    "Baltimore, MD:28.72:28.18|Portland, OR:15.92:24.71|Birmingham, AL:25.88:31.37|"
    "Pittsburgh, PA:27.78:27.54|Memphis, TN:24.99:30.48|New Orleans, LA:24.98:33.35|"
    "Louisville, KY:26.18:28.76|Savannah, GA:27.47:32.21|Chattanooga, TN:26.32:30.52|"
    "Boston, MA:30.26:26.48|San Diego, CA:17.46:31.82|Los Angeles, CA:17.16:31.08|"
    "Chicago, IL:25.66:26.75|Cleveland, OH:27.31:26.96|Oklahoma City, OK:22.91:30.29|"
    "St. Louis, MO:24.93:28.54|Boise, ID:17.71:25.77|Austin, TX:22.85:33.18|"
    "Denver, CO:20.84:27.92"
)

print("\nhubUSProjectionData:")
tokens = []
for item in HUBS.split("|"):
    label, ex, ey = item.split(":")
    lon = float(ex) * 3.6 - 180.0
    lat = 90.0 - float(ey) * 1.8
    x, y = to_view(albers(lon, lat))
    tokens.append(f"{label}:{100 * x / VIEW_W:.2f}:{100 * y / VIEW_H:.2f}")
print("|".join(tokens))
