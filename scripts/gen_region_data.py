#!/usr/bin/env python3
"""Generate the target country -> continent map used by the /board region lens.

Build-time only: it fetches public-domain Natural Earth 10m admin-0 country
polygons once, takes each feature's ISO_A2 code and CONTINENT label, and writes
internal/region/countries.go. The running app never fetches anything.

The alias table below covers ccTLD codes Natural Earth does not carry as
standalone features. Each entry is a documented geographic fact or a deliberate
"Unknown" for codes that are not a country at all (IDN pseudo-codes, the legacy
Soviet ccTLD). An unmapped code is always Unknown, never guessed from a name.

Usage: python3 scripts/gen_region_data.py [OUTPUT_GO]

Source: natural-earth-vector v5.1.2 (public domain), ne_10m_admin_0_countries.geojson
"""

from __future__ import annotations

import json
import os
import re
import sys
import urllib.request

SOURCE = (
    "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/"
    "geojson/ne_10m_admin_0_countries.geojson"
)
OUT = sys.argv[1] if len(sys.argv) > 1 else "internal/region/countries.go"

CONTINENTS = {
    "Africa", "Asia", "Europe", "North America", "Oceania",
    "South America", "Antarctica",
}

# ccTLD codes absent from Natural Earth as standalone features. The comment on
# each line is the reason for the mapping; "Unknown" is used where the code is
# not a place (XN is the IDN prefix, SU is a legacy supranational ccTLD).
ALIASES = {
    "AC": ("Africa", "Ascension Island, part of SH"),
    "CC": ("Oceania", "Cocos (Keeling) Islands, Australian external territory"),
    "CX": ("Oceania", "Christmas Island, Australian external territory"),
    "EU": ("Europe", "European Union ccTLD"),
    "GF": ("South America", "French Guiana, French overseas department"),
    "GP": ("North America", "Guadeloupe, French overseas department"),
    "GI": ("Europe", "Gibraltar"),
    "GS": ("South America", "South Georgia, UN M49 South America"),
    "HM": ("Antarctica", "Heard Island, Australian subantarctic territory"),
    "IO": ("Africa", "British Indian Ocean Territory, UN M49 Eastern Africa"),
    "MQ": ("North America", "Martinique, French overseas department"),
    "MU": ("Africa", "Mauritius"),
    "MV": ("Asia", "Maldives"),
    "RE": ("Africa", "Reunion, French overseas department"),
    "SC": ("Africa", "Seychelles"),
    "SH": ("Africa", "Saint Helena"),
    "SJ": ("Europe", "Svalbard, Norway"),
    "TF": ("Antarctica", "French Southern Territories, subantarctic"),
    "TK": ("Oceania", "Tokelau, New Zealand territory"),
    "UK": ("Europe", "United Kingdom ccTLD alias for GB"),
    "YT": ("Africa", "Mayotte, French overseas department"),
    "BV": ("Antarctica", "Bouvet Island, subantarctic Norwegian dependency"),
    "SU": ("Unknown", "legacy Soviet Union ccTLD, spans Europe and Asia"),
    "XN": ("Unknown", "IDN ccTLD pseudo-code, not a country"),
}


def main() -> None:
    with urllib.request.urlopen(SOURCE, timeout=60) as response:
        data = json.load(response)

    mapping: dict[str, str] = {}
    for feature in data["features"]:
        props = feature["properties"]
        continent = props.get("CONTINENT", "")
        if continent not in CONTINENTS:
            continue
        for key in ("ISO_A2", "ISO_A2_EH"):
            code = props.get(key, "")
            if re.fullmatch(r"[A-Za-z]{2}", code or ""):
                mapping.setdefault(code.upper(), continent)

    for code, (continent, _) in ALIASES.items():
        mapping[code] = continent

    lines = [
        "// Code generated by scripts/gen_region_data.py; DO NOT EDIT.",
        "// Source: Natural Earth 10m admin-0 countries v5.1.2 (public domain).",
        "// Continent names reuse the seven-continent vocabulary in vantagegeo.",
        "",
        "package region",
        "",
        'import "github.com/Greg-2600/netweather/internal/vantagegeo"',
        "",
        "const (",
        "\tAfrica       = vantagegeo.Africa",
        "\tAntarctica   = \"Antarctica\"",
        "\tAsia         = vantagegeo.Asia",
        "\tEurope       = vantagegeo.Europe",
        "\tNorthAmerica = vantagegeo.NorthAmerica",
        "\tOceania      = vantagegeo.Oceania",
        "\tSouthAmerica = vantagegeo.SouthAmerica",
        "\tUnknown      = vantagegeo.Unknown",
        ")",
        "",
        "// byCountry is generated, never edited by hand. A country code that is",
        "// not in this table is reported as Unknown by ForCountry.",
        "var byCountry = map[string]string{",
    ]
    for code in sorted(mapping):
        lines.append(f'\t"{code}": {mapping[code].replace(" ", "")},')
    lines.extend([
        "}",
        "",
        "// aliases explain the non-Natural-Earth codes above. They are kept in",
        "// the generated file so a reader can see why a ccTLD has a continent.",
        "var aliasReasons = map[string]string{",
    ])
    for code, (_, reason) in sorted(ALIASES.items()):
        lines.append(f'\t"{code}": "{reason}",')
    lines.extend(["}", ""])

    parent = os.path.dirname(OUT)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {OUT} ({len(mapping)} codes)")


if __name__ == "__main__":
    main()
